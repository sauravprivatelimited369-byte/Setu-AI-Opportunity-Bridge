export function useT(lang: Lang) {
  return strings[lang] ?? strings.en;
}

export function pickLocalized(
  opp: Opportunity,
  field: "title" | "company" | "location" | "description" | "requirements" | "eligibility" | "salaryLabel",
  lang: Lang
): string {
  if (lang === "hi") {
    const hiKey = (field + "Hi") as keyof Opportunity;
    return (opp[hiKey] as string) ?? (opp[field] as string) ?? "";
  }
  return (opp[field] as string) ?? "";
}
